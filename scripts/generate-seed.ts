// Generates supabase/migrations/0004_seed_reference.sql from the TypeScript exercise library and programme rules,
// so the database and the app can never drift apart. Run: npm run gen:seed
import { writeFileSync } from "node:fs";
import { EXERCISES } from "../src/lib/domain/exercises";
import { PHASE_LABELS, buildTemplates, weekPlan } from "../src/lib/domain/program";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (a: string[]) => (a.length ? `array[${a.map(q).join(",")}]::text[]` : `'{}'::text[]`);
const out: string[] = ["-- GENERATED by scripts/generate-seed.ts — do not edit by hand. Reference data only; contains no personal data.", "begin;"];

for (const e of EXERCISES) {
  out.push(
    `insert into public.exercise_library (id,name,category,description,muscles,requires,difficulty,load_type,per_side,starting_position,steps,breathing,common_mistakes,safety_notes,rep_min,rep_max,sets,rest_seconds,cautions) values (` +
      [q(e.id), q(e.name), q(e.category), q(e.description), arr(e.muscles), arr(e.requires), e.difficulty, q(e.loadType), e.perSide, q(e.startingPosition), arr(e.steps), q(e.breathing),
        arr(e.commonMistakes), arr(e.safetyNotes), e.repRange[0], e.repRange[1], e.sets, e.restSeconds, arr(e.cautions)].join(",") +
      `) on conflict (id) do nothing;`,
  );
}
for (const e of EXERCISES) {
  for (const v of e.progressions) out.push(`insert into public.exercise_variations values (${q(e.id)},${q(v)},'progression') on conflict do nothing;`);
  for (const v of e.regressions) out.push(`insert into public.exercise_variations values (${q(e.id)},${q(v)},'regression') on conflict do nothing;`);
}
const phases: [string, number, number | null][] = [["foundation", 1, 4], ["building", 5, 8], ["development", 9, 12], ["ongoing", 13, null]];
for (const [k, s, e] of phases) out.push(`insert into public.program_phases values (${q(k)},${q(PHASE_LABELS[k as keyof typeof PHASE_LABELS].name)},${q(PHASE_LABELS[k as keyof typeof PHASE_LABELS].blurb)},${s},${e ?? "null"}) on conflict do nothing;`);
for (let w = 1; w <= 13; w++) {
  const p = weekPlan(w, 7);
  out.push(`insert into public.program_weeks values (${w},${q(p.phase)},${p.sessions},${p.sets},${p.maxSets},${p.repRange[0]},${p.repRange[1]},${q(p.note)}) on conflict do nothing;`);
}
const full = buildTemplates({ items: ["mat", "chair", "light_dumbbells", "step", "bands", "bench"], dumbbellWeightsKg: [], bandLevels: [], other: "", updatedAt: "" },
  { mobility: "good", chairRise: "easy", armsOverhead: "full", balance: "confident", backDiscomfort: "none", kneeDiscomfort: "none", shoulderDiscomfort: "none", previousInjuries: "", conditions: "",
    hasProfessionalRestrictions: false, clearanceAcknowledged: false, answered: true, updatedAt: "" });
for (const t of full.templates) {
  out.push(`insert into public.workout_templates values (${q(t.letter)},${q(t.name)}) on conflict do nothing;`);
  t.slots.forEach((s, i) => out.push(`insert into public.workout_template_exercises values (${q(t.letter)},${q(s.slot)},${q(s.exerciseId)},${i},${!!s.optional}) on conflict do nothing;`));
}
out.push("commit;");
writeFileSync(new URL("../supabase/migrations/0004_seed_reference.sql", import.meta.url), out.join("\n") + "\n");
console.log(`Wrote ${out.length} statements`);
